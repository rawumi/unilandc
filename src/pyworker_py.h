#ifndef PYWORKER_PY_H
#define PYWORKER_PY_H
static const char k_pyworker_py[] =
    "import io, json, sys, contextlib\n"
    "\n"
    "def use_utf8(stream, errors):\n"
    "    try:\n"
    "        stream.reconfigure(encoding=\"utf-8\", errors=errors)\n"
    "    except Exception:\n"
    "        pass\n"
    "\n"
    "use_utf8(sys.stdin, \"replace\")\n"
    "use_utf8(sys.stdout, \"replace\")\n"
    "use_utf8(sys.stderr, \"replace\")\n"
    "\n"
    "py_ns = {\"__name__\": \"uniland_embedded\"}\n"
    "_wid = [1000]\n"
    "\n"
    "_RAW = sys.stdout\n"
    "\n"
    "def send(obj):\n"
    "    _RAW.write(json.dumps(obj, ensure_ascii=True) + \"\\n\")\n"
    "    _RAW.flush()\n"
    "\n"
    "def rpc(op, **kw):\n"
    "    _wid[0] += 1\n"
    "    rid = _wid[0]\n"
    "    msg = {\"kind\": \"req\", \"id\": rid, \"op\": op}\n"
    "    msg.update(kw)\n"
    "    send(msg)\n"
    "    while True:\n"
    "        line = sys.stdin.readline()\n"
    "        if not line:\n"
    "            raise RuntimeError(\"host closed\")\n"
    "        resp = json.loads(line)\n"
    "        if resp.get(\"id\") == rid:\n"
    "            if resp.get(\"ok\"):\n"
    "                return resp.get(\"value\")\n"
    "            raise RuntimeError(resp.get(\"err\", \"bridge error\"))\n"
    "\n"
    "class UniBridge:\n"
    "\n"
    "    def __getattr__(self, key):\n"
    "        r = rpc(\"uni_get\", k=key)\n"
    "        return dec(r)\n"
    "\n"
    "    def __setattr__(self, key, value):\n"
    "        try:\n"
    "            del self.__dict__[key]\n"
    "        except KeyError:\n"
    "            pass\n"
    "        object.__setattr__(self, \"_setkey\", key)\n"
    "        rpc(\"uni_set\", k=key, v=value)\n"
    "        object.__delattr__(self, \"_setkey\")\n"
    "\n"
    "    def __getitem__(self, key):\n"
    "        r = rpc(\"uni_get\", k=key)\n"
    "        return dec(r)\n"
    "\n"
    "    def __setitem__(self, key, value):\n"
    "        rpc(\"uni_set\", k=key, v=value)\n"
    "\n"
    "    def call(self, name, *args):\n"
    "        r = rpc(\"uni_call\", k=name, args=[enc(a) for a in args])\n"
    "        return dec(r)\n"
    "\n"
    "uni_bridge = UniBridge()\n"
    "py_ns[\"uni\"] = uni_bridge\n"
    "\n"
    "def enc(v):\n"
    "    if v is None:\n"
    "        return None\n"
    "    if v is True:\n"
    "        return True\n"
    "    if v is False:\n"
    "        return False\n"
    "    if isinstance(v, int):\n"
    "        return {\"T\": \"int\", \"v\": str(v)}\n"
    "    if isinstance(v, float):\n"
    "        f = repr(v)\n"
    "        if f in (\"inf\", \"-inf\", \"nan\"):\n"
    "            return {\"T\": \"floats\", \"v\": f}\n"
    "        return {\"T\": \"float\", \"v\": repr(v)}\n"
    "    if isinstance(v, str):\n"
    "        return {\"T\": \"str\", \"v\": v}\n"
    "    if isinstance(v, (list, tuple)):\n"
    "        return {\"T\": \"list\", \"v\": [enc(x) for x in v]}\n"
    "    if isinstance(v, dict):\n"
    "        return {\"T\": \"obj\", \"k\": [str(k) for k in v], \"v\": {str(k): enc(x) for k, x in v.items()}}\n"
    "    return {\"T\": \"func\"}\n"
    "\n"
    "def dec(w):\n"
    "    if w is None or isinstance(w, (bool, int, float)):\n"
    "        return w\n"
    "    if isinstance(w, str):\n"
    "        return w\n"
    "    if isinstance(w, list):\n"
    "        return [dec(x) for x in w]\n"
    "    if isinstance(w, dict):\n"
    "        t = w.get(\"T\")\n"
    "        if t == \"int\":\n"
    "            return int(w[\"v\"])\n"
    "        if t == \"float\":\n"
    "            return float(w[\"v\"])\n"
    "        if t == \"str\":\n"
    "            return w[\"v\"]\n"
    "        if t == \"list\":\n"
    "            return [dec(x) for x in w[\"v\"]]\n"
    "        if t == \"obj\":\n"
    "            src = w.get(\"v\", {})\n"
    "            keys = w.get(\"k\")\n"
    "            if isinstance(keys, list):\n"
    "                return {k: dec(src[k]) for k in keys}\n"
    "            return {k: dec(x) for k, x in src.items()}\n"
    "        if t == \"null\":\n"
    "            return None\n"
    "        if t == \"func\":\n"
    "            return None\n"
    "    return None\n"
    "\n"
    "def emit_out(text):\n"
    "    if text:\n"
    "        send({\"kind\": \"out\", \"text\": text})\n"
    "\n"
    "def emit_err(text):\n"
    "    if text:\n"
    "        send({\"kind\": \"err\", \"text\": text})\n"
    "\n"
    "def run_exec(code):\n"
    "    buf_out, buf_err = io.StringIO(), io.StringIO()\n"
    "    with contextlib.redirect_stdout(buf_out), contextlib.redirect_stderr(buf_err):\n"
    "        try:\n"
    "            exec(code, py_ns)\n"
    "            ok = True\n"
    "            err = None\n"
    "        except Exception as e:\n"
    "            ok = False\n"
    "            err = str(e)\n"
    "    emit_out(buf_out.getvalue())\n"
    "    emit_err(buf_err.getvalue())\n"
    "    return ok, err\n"
    "\n"
    "def run_eval(code):\n"
    "    buf_out, buf_err = io.StringIO(), io.StringIO()\n"
    "    with contextlib.redirect_stdout(buf_out), contextlib.redirect_stderr(buf_err):\n"
    "        try:\n"
    "            value = eval(code, py_ns)\n"
    "            ok = True\n"
    "            err = None\n"
    "        except Exception as e:\n"
    "            ok = False\n"
    "            err = str(e)\n"
    "            value = None\n"
    "    emit_out(buf_out.getvalue())\n"
    "    emit_err(buf_err.getvalue())\n"
    "    return ok, err, value\n"
    "\n"
    "def main_loop():\n"
    "    while True:\n"
    "        line = sys.stdin.readline()\n"
    "        if not line:\n"
    "            break\n"
    "        try:\n"
    "            msg = json.loads(line)\n"
    "        except Exception:\n"
    "            continue\n"
    "        op = msg.get(\"op\")\n"
    "        rid = msg.get(\"id\")\n"
    "        if op == \"shutdown\":\n"
    "            break\n"
    "        if op == \"exec\":\n"
    "            ok, err = run_exec(msg[\"code\"])\n"
    "            send({\"id\": rid, \"ok\": ok, \"err\": err})\n"
    "        elif op == \"eval\":\n"
    "            ok, err, value = run_eval(msg[\"code\"])\n"
    "            send({\"id\": rid, \"ok\": ok, \"err\": err, \"value\": enc(value)})\n"
    "        else:\n"
    "            send({\"id\": rid, \"ok\": False, \"err\": \"unknown op\"})\n"
    "\n"
    "if __name__ == \"__main__\":\n"
    "    main_loop()\n"
    "\n"
    ;
#endif
